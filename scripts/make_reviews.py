# Распределение оценок. Не равномерное: у товара, который люди покупают
# добровольно, пятёрок всегда больше, а единицы редки. Равномерное
# распределение сразу выдаёт сгенерированные данные.
RATING_WEIGHTS = [(5, 56), (4, 27), (3, 10), (2, 5), (1, 2)]


def make_customers(count: int, rng: random.Random) -> list[dict]:
    """Профили покупателей с уникальной почтой.

    Уникальность важна: в базе на почте стоит UNIQUE, и дубль
    в демо-данных упал бы прямо при заливке.
    """
    seen: set[str] = set()
    people = []
    while len(people) < count:
        female = rng.random() < 0.42
        first = rng.choice(FIRST_F if female else FIRST_M)
        last = rng.choice(LAST) + ("а" if female else "")
        login = f"{translit(first)}.{translit(last)}{rng.randint(1, 99)}"
        # Домен example.com зарезервирован стандартом под примеры —
        # письмо по такому адресу гарантированно никуда не уйдёт.
        email = f"{login}@example.com"
        if email in seen:
            continue
        seen.add(email)
        people.append({
            "name": f"{first} {last[0]}." if rng.random() < 0.55 else f"{first} {last}",
            "email": email,
            "city": rng.choice(CITIES),
        })
    return people


TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c",
    "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e",
    "ю": "yu", "я": "ya",
}


def translit(word: str) -> str:
    return "".join(TRANSLIT.get(ch, ch) for ch in word.lower())


def pick_rating(rng: random.Random) -> int:
    values, weights = zip(*RATING_WEIGHTS, strict=True)
    return rng.choices(values, weights=weights, k=1)[0]


def make_body(product: dict, rating: int, rng: random.Random) -> str:
    """Собирает текст из двух-трёх непохожих фраз.

    Фразы берутся `sample`, а не `choice`: `choice` может выдать одну
    и ту же строку дважды, и отзыв получится с повтором.
    """
    pool = BY_RATING.get(product["category"], BY_RATING["Игры"])[rating]
    count = min(len(pool), rng.choice([2, 2, 3]))
    parts = rng.sample(pool, count)

    # Примерно у трети отзывов есть фраза про доставку — как в жизни:
    # часть людей пишет про товар, часть заодно про магазин.
    if rng.random() < 0.34:
        parts.append(rng.choice(SHIPPING if rating >= 4 else SHIPPING_BAD))

    text = " ".join(parts)
    return (text.replace("{title}", product["title"])
                .replace("{platform}", product["platform"] or "консоли")
                .replace("{dev}", product["developer"] or "разработчики"))


def main() -> int:
    parser = argparse.ArgumentParser(description="генератор отзывов")
    parser.add_argument("--per", type=int, default=13,
                        help="среднее число отзывов на товар (минимум 10)")
    parser.add_argument("--seed", type=int, default=20260914,
                        help="зерно: одно и то же зерно даёт один и тот же набор")
    args = parser.parse_args()

    # Фиксированное зерно — чтобы перегенерация не меняла весь файл
    # целиком. Иначе каждый запуск давал бы полностью новый набор,
    # и в истории изменений это выглядело бы как «переписано всё».
    rng = random.Random(args.seed)

    products = json.loads(CATALOG.read_text(encoding="utf-8"))["products"]
    people = make_customers(140, rng)

    reviews = []
    for product in products:
        # Разброс вокруг заданного числа, но не меньше десяти:
        # одинаковое количество у всех товаров выглядит неестественно.
        count = max(10, args.per + rng.randint(-2, 4))
        authors = rng.sample(people, count)  # один человек — один отзыв на товар
        for person in authors:
            rating = pick_rating(rng)
            reviews.append({
                "author": person["name"],
                "email": person["email"],
                "rating": rating,
                "sku": product["sku"],
                "title": rng.choice(TITLES[rating]),
                "body": make_body(product, rating, rng),
            })

    rng.shuffle(reviews)

    CUSTOMERS.write_text(json.dumps({
        "_комментарий": [
            "ВЫДУМАННЫЕ профили покупателей для учебного проекта.",
            "В базе помечены флагом is_demo и удаляются одним запросом.",
            "Домен example.com зарезервирован стандартом под примеры.",
        ],
        "customers": people,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    REVIEWS.write_text(json.dumps({
        "_комментарий": [
            "ВЫДУМАННЫЕ отзывы. Магазина не существует, покупателей нет.",
            "Собраны скриптом scripts/make_reviews.py из заготовок.",
            "",
            "В базе помечены флагом is_demo — спутать с настоящими нельзя,",
            "и удалить можно одним запросом: DELETE FROM reviews WHERE is_demo",
            "",
            "email связывает отзыв с профилем покупателя (data/customers.json),",
            "sku — с товаром каталога.",
        ],
        "reviews": reviews,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    per_product: dict[str, int] = {}
    for review in reviews:
        per_product[review["sku"]] = per_product.get(review["sku"], 0) + 1
    print(f"покупателей: {len(people)}")
    print(f"отзывов: {len(reviews)}  "
          f"(на товар от {min(per_product.values())} до {max(per_product.values())})")
    average = sum(r["rating"] for r in reviews) / len(reviews)
    print(f"средняя оценка: {average:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
